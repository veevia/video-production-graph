def _set(d: dict[str, Any], dotted: str, value: Any) -> None:
    *head, last = dotted.split(".")
    for part in head:
        d = d.setdefault(part, {})
    d[last] = copy.deepcopy(value)


def _append(d: dict[str, Any], dotted: str, items: list[Any]) -> None:
    *head, last = dotted.split(".")
    for part in head:
        d = d.setdefault(part, {})
    have = d.setdefault(last, [])
    d[last] = have + [copy.deepcopy(x) for x in items if x not in have]


def build(default: dict[str, Any]) -> dict[str, Any]:
    """The quality workflow as data: the default graph with the overlay applied."""
    data = copy.deepcopy(default)
    data.update(TOP)
    for s in data["subgraphs"]:
        if s["id"] == "planning":
            s.update(copy.deepcopy(PLANNING))
    by_id = {n["id"]: n for n in data["nodes"]}
    for nid, patch in NODES.items():
        node = by_id[nid]   # a KeyError here means the default graph renamed a node the overlay extends
        for dotted, items in patch.get("append", {}).items():
            _append(node, dotted, items)
        for dotted, value in patch.get("set", {}).items():
            _set(node, dotted, value)
        if patch.get("instructions"):
            node["instructions"] = node["instructions"].rstrip() + " " + patch["instructions"]
    data["nodes"] += copy.deepcopy(NEW_NODES)
    missing = REMOVED_EDGES - {e["id"] for e in data["edges"]}
    if missing:
        raise ValueError(f"the overlay removes edges the default graph no longer has: {sorted(missing)}")
    data["edges"] = [e for e in data["edges"] if e["id"] not in REMOVED_EDGES] + copy.deepcopy(NEW_EDGES)
    return data


def text(default_path=DEFAULT_PATH) -> str:
    """graph/workflow-quality.yaml as `python -m vpg docs` writes it."""
    data = build(yaml.safe_load(default_path.read_text()))
    return HEADER + yaml.safe_dump(data, sort_keys=False, allow_unicode=True, width=4096, default_flow_style=None)
