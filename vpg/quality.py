def _edge(eid, a, b, kind, transition, when, transfers, threshold, branching, on_fail, max_traversals=None):
    e = {"id": eid, "from": a, "to": b, "kind": kind, "transition": transition, "when": when, "transfers": transfers,
         "threshold": threshold, "branching": branching, "on_fail": on_fail}
    if max_traversals:
        e["max_traversals"] = max_traversals
    return e


