def esc(x) -> str:
    """Markdown-safe: escape &, <, > and table pipes; keep quotes readable."""
    return html.escape(str(x), quote=False).replace("|", "\\|")


GEN = "<!-- generated by `python -m vpg docs` from graph/workflow.yaml; do not hand-edit -->\n"


def _list(xs) -> str:
    return "<br>".join(esc(str(x)) for x in xs) or "—"


def node_catalog(wf: Workflow) -> str:
    idx = GraphIndex(wf)
    rubrics = load_rubrics(PKG_ROOT)
    out = [GEN, "# Node catalog", "", f"> **TL;DR:** {len(wf.nodes)} nodes, each with the 19 fields the brief requires. "
           "Upstream and downstream are derived from the edges.", ""]
    for n in sorted(wf.nodes, key=lambda x: x.num):
        up = [e for e in idx.incoming(n.id)]
        down = idx.outgoing(n.id)
        dims = [f"{d['id']} ({d['check']['type']})" for r in n.rubric for d in rubrics[r]["dimensions"]]
        rows = [
            ("1. Node ID and name", f"`{n.id}` — N{n.num:02d} {n.name} · kind `{n.kind.value}` · phase {n.phase} · subgraph `{n.subgraph}`"),
            ("2. Purpose", n.purpose),
            ("3. Required inputs", _list(n.inputs)),
            ("4. Relevant context", _list(n.context)),
            ("5. State read", _list(n.state_read)),
            ("6. State written", _list(n.state_write)),
            ("7. Responsible agent", f"`{n.agent}` (agents/{n.agent}.yaml)"),
            ("8. Skills and tools", "Skills: " + (", ".join(n.skills) or "—") + "<br>Tools: " + (", ".join(n.tools) or "—")
             + (f"<br>Run: `{n.run.tool}`" if n.run and n.run.tool else "") + (" · project command hook" if n.run and n.run.command_hook else "")),
            ("9. Execution instructions", esc(n.instructions) + (f"<br>Prompt: `{n.prompt}`" if n.prompt else "")),
            ("10. Expected outputs and artifacts", _list(f"{o.key} ({o.kind}{', ' + o.schema_name if o.schema_name else ''}{', per item' if o.per_item else ''}"
                                                          f"{', optional' if not o.required else ''}) → {o.state_path or ', '.join(o.state_fields.values()) or 'artifact only'}"
                                                          for o in n.outputs)),
            ("11. Completion criteria", _list(f"[{c.type}{': ' + c.fn if c.fn else ''}] {c.description}" for c in n.completion)),
            ("12. Evaluation rubric", ", ".join(n.rubric) + "<br>" + _list(dims)),
            ("13. Failure conditions", _list(n.failure_conditions)),
            ("14. Retry behavior", f"max {n.retry.max_attempts} consecutive attempts — {esc(n.retry.behavior)}"),
            ("15. Maximum retry or escalation policy", f"{esc(n.escalation.after)} → {n.escalation.to}: {esc(n.escalation.report)}"),
            ("16. Human-review requirements", ("**Required** — " if n.human_review.required else "Not required — ") + esc(n.human_review.decision)
             + (f" ({n.human_review.approver}; outcomes {', '.join(n.human_review.outcomes)})" if n.human_review.required else "")),
            ("17. Upstream dependencies", _list(f"{e.source} ({e.kind.value}, when `{e.when}`)" for e in up)),
            ("18. Downstream transitions", _list(f"{e.id}: → {e.target} ({e.kind.value}, when `{e.when}`)" for e in down)),
            ("19. Provenance and logging", _list(n.provenance + ["Ledger: node_dispatched, node_passed/node_failed, checkpoint"])),
        ]
        extra = []
        if n.controls.read or n.controls.write:
            extra.append(f"Control documents — read: {', '.join(n.controls.read) or '—'}; write: {', '.join(n.controls.write) or '—'}; "
                         f"lock on approval: {', '.join(n.controls.lock_on_approval) or '—'}")
        if n.resources:
            extra.append(f"Resources (single-flight if listed in policies): {', '.join(n.resources)}")
        if n.map_over:
            extra.append(f"Fan-out: one work item per entry of `{n.map_over}`")
        if n.gate:
            extra.append(f"Engine gate hook: `{n.gate}`")
        out += [f"## N{n.num:02d} {n.name}", "", "| Field | Definition |", "|---|---|"]
        out += [f"| {k} | {v} |" for k, v in rows]
        out += ([""] + [f"- {x}" for x in extra] if extra else []) + [""]
    return "\n".join(out)


def edge_catalog(wf: Workflow) -> str:
    out = [GEN, "# Edge catalog", "", f"> **TL;DR:** {len(wf.edges)} edges: "
           f"{sum(e.kind == EdgeKind.FLOW for e in wf.edges)} flow, {sum(e.kind == EdgeKind.LOOP for e in wf.edges)} bounded loop, "
           f"{sum(e.kind == EdgeKind.ESCALATE for e in wf.edges)} escalate; "
           f"{sum(e.transition == 'deterministic' for e in wf.edges)} deterministic and {sum(e.transition == 'conditional' for e in wf.edges)} conditional.", "",
           "| Edge | Source → destination | Transition condition | Data or artifacts transferred | Quality threshold | Branching logic | Retry, rollback or escalation |",
           "|---|---|---|---|---|---|---|"]
    for e in wf.edges:
        cond = f"{e.kind.value} · {e.transition} · when `{e.when}`" + (f" · max {e.max_traversals} traversals" if e.max_traversals else "")
        out.append(f"| {e.id} | {e.source} → {e.target} | {cond} | {_list(e.transfers)} | {esc(e.threshold)} | "
                   f"{esc(e.branching)} | {esc(e.on_fail)} |")
    return "\n".join(out) + "\n"


def control_access(wf: Workflow, docs: list[str] | None = None) -> str:
    docs = list(docs or CONTROL_DOCS)
    out = [GEN, "# Control-document access", "",
           "> **TL;DR:** who may read (R), write (W) or lock on approval (L) each control document. Every other edit is reverted by "
           "the engine and fails the attempt, and an approved document changes only through an approved change request.", "",
           "| Node | " + " | ".join(docs) + " |", "|---|" + "---|" * len(docs)]
    for n in sorted(wf.nodes, key=lambda x: x.num):
        cells = []
        for d in docs:
            c = ("R" if d in n.controls.read else "") + ("W" if d in n.controls.write else "") + ("L" if d in n.controls.lock_on_approval else "")
            cells.append(c or "·")
        out.append(f"| N{n.num:02d} {n.name} | " + " | ".join(cells) + " |")
    return "\n".join(out) + "\n"


def agent_catalog() -> str:
    out = [GEN, "# Agent catalog", "", "> **TL;DR:** 18 specialised roles. Each is bound to graph nodes and to real workspace skills, with explicit decision authority and escalation.", ""]
    for p in sorted((PKG_ROOT / "agents").glob("*.yaml")):
        a = yaml.safe_load(p.read_text())
        out += [f"## {a['name']} (`{a['id']}`)", "", f"**Responsibility:** {a['responsibility']}", "",
                "| Field | Definition |", "|---|---|",
                f"| Nodes | {_list(a['nodes'])} |", f"| Inputs and allowable context | {_list(a['inputs_allowed'])}<br>Controls read: {', '.join(a['controls']['read']) or '—'}; write: {', '.join(a['controls']['write']) or '—'} |",
                f"| Skills and tools | Skills: {', '.join(a['skills']) or '—'}<br>Tools: {', '.join(a['tools']) or '—'} |",
                f"| Outputs | {', '.join(a['outputs'])} |", f"| Decision authority | {esc(a['decision_authority'])} |",
                f"| Constraints | {_list(a['constraints'])} |", f"| Evaluation criteria | rubrics: {', '.join(a['evaluation'])} |",
                f"| Escalation | {esc(a['escalation']['when'])} → {a['escalation']['to']} ({esc(a['escalation']['how'])}) |",
                f"| Runtime binding | {esc(a['runtime_binding'])} |", ""]
    return "\n".join(out)


def mermaid(wf: Workflow) -> str:
    lines = ["flowchart LR", "  START((START))", "  END((END))", "  ESC{{\"@escalate → the project owner\"}}"]
    for s in wf.subgraphs:
        lines.append(f"  subgraph {s.id}[\"{s.name}\"]")
        for nid in s.nodes:
            n = wf.node(nid)
            shape = ("[[", "]]") if n.kind.value == "tool" else ("[/", "/]") if n.kind.value == "review" else ("[", "]")
            label = f"N{n.num:02d} {n.name}" + (" 👤" if n.human_review.required else "")
            lines.append(f"    {nid}{shape[0]}\"{label}\"{shape[1]}")
        lines.append("  end")
    for e in wf.edges:
        a = e.source
        b = {"@escalate": "ESC"}.get(e.target, e.target)
        lab = "" if e.when in ("*", "pass") else f"|{e.when.replace('target:', '→ ')}|"
        arrow = {"flow": "-->", "loop": "-.->", "escalate": "==>"}[e.kind.value]
        lines.append(f"  {a} {arrow}{lab} {b}")
    lines += ["  classDef tool fill:#EEF1F4,stroke:#5A6572", "  classDef review fill:#FFF6E0,stroke:#B7791F",
              "  class " + ",".join(n.id for n in wf.nodes if n.kind.value == "tool") + " tool",
              "  class " + ",".join(n.id for n in wf.nodes if n.kind.value == "review") + " review"]
    return "\n".join(lines) + "\n"


def svg(wf: Workflow) -> str:
    """A layered left-to-right layout (longest path over flow edges), with no external dependencies."""
    idx = GraphIndex(wf)
    layer: dict[str, int] = {}
    for nid in idx.topo:
        preds = [e.source for e in idx.incoming(nid, EdgeKind.FLOW) if e.source in layer]
        layer[nid] = max((layer[p] + 1 for p in preds), default=1)
    cols: dict[int, list[str]] = {}
    for nid in sorted(layer, key=lambda n: wf.node(n).num):
        cols.setdefault(layer[nid], []).append(nid)
    W, H, GX, GY, PAD = 200, 58, 60, 26, 40
    pos = {}
    maxrows = max(len(v) for v in cols.values())
    for c, ids in cols.items():
        top = PAD + 70 + (maxrows - len(ids)) * (H + GY) / 2
        for r, nid in enumerate(ids):
            pos[nid] = (PAD + 90 + (c - 1) * (W + GX), top + r * (H + GY))
    width = PAD * 2 + 90 + len(cols) * (W + GX) + 60
    height = PAD * 2 + 70 + maxrows * (H + GY) + 90
    pos["START"] = (PAD, pos[wf.edges[0].target][1])
    pos["END"] = (width - PAD - 60, pos[next(e.source for e in wf.edges if e.target == "END")][1])
    pos["@escalate"] = (width / 2 - 70, height - PAD - 50)
    fill = {"agent": "#FFFFFF", "tool": "#EEF1F4", "review": "#FFF6E0"}
    parts = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{int(width)}" height="{int(height)}" viewBox="0 0 {int(width)} {int(height)}" '
             'font-family="Helvetica, Arial, sans-serif">',
             '<defs><marker id="a" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" orient="auto-start-reverse">'
             '<path d="M0,0 L10,5 L0,10 z" fill="#1A1F26"/></marker>'
             '<marker id="l" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" orient="auto-start-reverse">'
             '<path d="M0,0 L10,5 L0,10 z" fill="#C4151C"/></marker></defs>',
             f'<rect width="100%" height="100%" fill="#FAFBFC"/>',
             f'<text x="{PAD}" y="{PAD + 10}" font-size="22" font-weight="700" fill="#1A1F26">{html.escape(wf.name)} v{wf.version}</text>',
             f'<text x="{PAD}" y="{PAD + 36}" font-size="13" fill="#5A6572">solid = flow (join = all) · dashed red = bounded loop · dotted = escalate · '
             'white = agent · grey = tool · amber = review · thick red border = human gate</text>']

    def box_edge(nid, side):
        x, y = pos[nid]
        w = W if nid not in ("START", "END", "@escalate") else (60 if nid != "@escalate" else 140)
        return (x + (w if side == "r" else 0), y + H / 2)

    for e in wf.edges:
        (x1, y1), (x2, y2) = box_edge(e.source, "r"), box_edge(e.target, "l")
        if e.kind == EdgeKind.FLOW:
            mx = (x1 + x2) / 2
            parts.append(f'<path d="M{x1:.0f},{y1:.0f} C{mx:.0f},{y1:.0f} {mx:.0f},{y2:.0f} {x2:.0f},{y2:.0f}" fill="none" stroke="#1A1F26" '
                         f'stroke-width="1.4" marker-end="url(#a)"/>')
        elif e.kind == EdgeKind.LOOP:
            sx, sy = pos[e.source][0] + W / 2, pos[e.source][1]
            tx, ty = pos[e.target][0] + W / 2, pos[e.target][1]
            lift = 40 + abs(sx - tx) * 0.06
            parts.append(f'<path d="M{sx:.0f},{sy:.0f} C{sx:.0f},{sy - lift:.0f} {tx:.0f},{ty - lift:.0f} {tx:.0f},{ty:.0f}" fill="none" stroke="#C4151C" '
                         f'stroke-width="1.2" stroke-dasharray="6 4" marker-end="url(#l)" opacity="0.8"><title>{e.id} {html.escape(e.when)}</title></path>')
        else:
            parts.append(f'<path d="M{pos[e.source][0] + W / 2:.0f},{pos[e.source][1] + H:.0f} L{pos["@escalate"][0] + 70:.0f},{pos["@escalate"][1]:.0f}" '
                         f'fill="none" stroke="#5A6572" stroke-width="1.2" stroke-dasharray="2 4" marker-end="url(#a)"/>')
    for nid in ("START", "END"):
        x, y = pos[nid]
        parts.append(f'<rect x="{x}" y="{y}" width="60" height="{H}" rx="29" fill="#1A1F26"/>'
                     f'<text x="{x + 30}" y="{y + H / 2 + 5}" font-size="13" fill="#FFF" text-anchor="middle" font-weight="700">{nid}</text>')
    x, y = pos["@escalate"]
    parts.append(f'<rect x="{x}" y="{y}" width="140" height="{H}" rx="8" fill="#FFF" stroke="#5A6572" stroke-dasharray="2 3"/>'
                 f'<text x="{x + 70}" y="{y + H / 2 + 5}" font-size="13" text-anchor="middle" fill="#1A1F26">@escalate → the project owner</text>')
    for n in wf.nodes:
        x, y = pos[n.id]
        stroke, sw = ("#C4151C", 3) if n.human_review.required else ("#5A6572", 1.2)
        parts.append(f'<rect x="{x}" y="{y}" width="{W}" height="{H}" rx="8" fill="{fill[n.kind.value]}" stroke="{stroke}" stroke-width="{sw}">'
                     f'<title>{html.escape(n.purpose)}</title></rect>')
        name = n.name if len(n.name) <= 30 else n.name[:29] + "…"
        parts.append(f'<text x="{x + 10}" y="{y + 22}" font-size="12" font-weight="700" fill="#1A1F26">N{n.num:02d}</text>'
                     f'<text x="{x + 44}" y="{y + 22}" font-size="12" fill="#1A1F26">{html.escape(name)}</text>'
                     f'<text x="{x + 10}" y="{y + 42}" font-size="11" fill="#5A6572">{n.kind.value} · {html.escape(n.agent)}</text>')
    parts.append("</svg>")
    return "\n".join(parts) + "\n"


