def principles() -> str:
    from .memory import RuleBase, enforcement
    rb = RuleBase()
    out = [GEN.replace("graph/workflow.yaml", "knowledge/rules.json"), "# Workflow policy templates", "",
           "Reusable defaults for new projects, not a record of production observations or human approvals.",
           "A built-in policy states its default enforcement explicitly. Private projects may copy and govern "
           "their own rules; no project history is included here.", "",
           f"Policy pack v{rb.data['version']}: {len(rb.rules)} reusable rules.", ""]
    for category, title in CATEGORY_TITLES.items():
        rules = [r for r in rb.rules if r["category"] == category]
        if not rules:
            continue
        out += [f"## {title}", ""]
        for rule in rules:
            check = rule["check"]
            method = (f"tool `{check['fn']}`" if check.get("type") == "tool"
                      else "a named human decides" if check.get("type") == "human" else "reviewer cases")
            out += [f"### {rule['id']} — {esc(rule['statement'])}", "",
                    f"- **Check:** {method}; rubric dimensions: {', '.join(rule.get('rubric_dimensions', [])) or 'none'}",
                    f"- **Default:** {enforcement(rule)}"]
            if rule.get("threshold"):
                out.append(f"- **Threshold:** {esc(str(rule['threshold']))}")
            for kind in ("never", "always"):
                out += [f"  - **{kind.title()}:** {esc(case)}" for case in check.get(kind, [])]
            if check.get("test"):
                out.append(f"- **Synthetic regression:** `{check['test']}`")
            out.append("")
    return "\n".join(out).rstrip() + "\n"


NODES_START, NODES_END = "<!-- NODES:START -->", "<!-- NODES:END -->"


def graph_spec(wf: Workflow) -> str:
    """docs/graph-spec.md is hand-written except its node table, which is regenerated between the markers."""
    text = (PKG_ROOT / "docs" / "graph-spec.md").read_text()
    idx = GraphIndex(wf)
    rows = ["| N | Node | Kind | Subgraph | Human gate | Gate hook | Loops back to |", "|---|---|---|---|---|---|---|"]
    for n in sorted(wf.nodes, key=lambda n: n.num):
        loops = sorted({e.target for e in idx.outgoing(n.id) if e.kind == EdgeKind.LOOP})
        rows.append(f"| {n.num:02d} | `{n.id}` — {esc(n.name)} | {n.kind.value} | {n.subgraph} | "
                    f"{'yes' if n.human_review.required else '—'} | {n.gate or '—'} | {', '.join(loops) or '—'} |")
    pre, rest = text.split(NODES_START, 1)
    return pre + NODES_START + "\n" + "\n".join(rows) + "\n" + NODES_END + rest.split(NODES_END, 1)[1]


CONSTRAINT_KEYS = ("minItems", "maxItems", "minLength", "maxLength", "pattern", "minimum", "maximum", "exclusiveMinimum",
                   "exclusiveMaximum", "description")


def _annotation_at(model: type, path: str) -> Any:
    """The type annotation of a dotted state path, e.g. inputs.sources → list[SourceRef]."""
    cur, ann = model, None
    for part in path.split("."):
        ann = cur.model_fields[part].annotation
        cur = ann if isinstance(ann, type) and issubclass(ann, BaseModel) else None
    return ann


def _overlay(target: dict[str, Any], authored: dict[str, Any], defs: dict[str, Any]) -> None:
    """Carry the authored schema's extra constraints onto the model-derived schema at the matching paths."""
    while "$ref" in target:
        target = defs[target["$ref"].split("/")[-1]]
    if "anyOf" in target:
        target = next((b for b in target["anyOf"] if b.get("type") != "null"), target)
        while "$ref" in target:
            target = defs[target["$ref"].split("/")[-1]]
    for key in CONSTRAINT_KEYS:
        if key in authored:
            target[key] = authored[key]
    if authored.get("required") and target.get("properties"):
        target["required"] = sorted(set(target.get("required", [])) | {r for r in authored["required"] if r in target["properties"]})
    if isinstance(authored.get("items"), dict) and isinstance(target.get("items"), dict):
        _overlay(target["items"], authored["items"], defs)
    for key, sub in (authored.get("properties") or {}).items():
        if key in (target.get("properties") or {}):
            _overlay(target["properties"][key], sub, defs)


def artifact_schemas(wf: Workflow) -> dict[Path, str]:
    """Artifact properties that feed the typed state are generated from vpg/models.py, so an artifact the schema accepts
    is one the typed state accepts (extra keys included). Authored constraints such as minItems are kept."""
    fields: dict[str, dict[str, str]] = {}
    for n in wf.nodes:
        for o in n.outputs:
            if o.schema_name and o.state_fields:
                fields.setdefault(o.schema_name, {}).update(o.state_fields)
    out = {}
    for name, mapping in sorted(fields.items()):
        path = PKG_ROOT / "schemas" / "artifacts" / f"{name}.schema.json"
        schema = json.loads(path.read_text())
        authored = schema.get("x-authored", {}) or {k: schema["properties"].get(k, {}) for k in mapping}
        defs: dict[str, Any] = {}
        made = []
        for field, state_path in sorted(mapping.items()):
            generated = TypeAdapter(_annotation_at(ProjectState, state_path)).json_schema(ref_template="#/$defs/{model}")
            models = generated.pop("$defs", {})
            if not models:   # a scalar or free-form value: the typed state accepts it as authored, so keep the stricter authored schema
                schema["properties"][field] = json.loads(json.dumps(authored.get(field, {})))
                continue
            defs.update(models)
            _overlay(generated, authored.get(field, {}), defs)
            schema["properties"][field] = generated
            made.append(field)
        for key in ("$defs", "x-authored", "x-generated"):
            schema.pop(key, None)
        if made:
            schema["$defs"] = dict(sorted(defs.items()))
            schema["x-authored"] = {k: authored[k] for k in made if k in authored}   # re-applied on every regeneration
            schema["x-generated"] = (f"properties {made} are generated from vpg/models.py by `python -m vpg docs`; "
                                     "change the model or x-authored, not these properties")
        out[path] = json.dumps(schema, indent=1, ensure_ascii=False) + "\n"
    return out


