def mermaid(wf: Workflow) -> str:
    lines = ["flowchart LR", "  START((START))", "  END((END))", "  ESC{{\"@escalate → Wei\"}}"]
    for s in wf.subgraphs:
        lines.append(f"  subgraph {s.id}[\"{s.name}\"]")
        for nid in s.nodes:
            n = wf.node(nid)
            shape = ("[[", "]]") if n.kind.value == "tool" else ("[/", "/]") if n.kind.value == "review" else ("[", "]")
            label = f"N{n.num:02d} {n.name}" + (" 👤" if n.human_review.required else "")
            lines.append(f"    {nid}{shape[0]}\"{label}\"{shape[1]}")
        lines.append("  end")
    for e in wf.edges:
        a = e.source
        b = {"@escalate": "ESC"}.get(e.target, e.target)
        lab = "" if e.when in ("*", "pass") else f"|{e.when.replace('target:', '→ ')}|"
        arrow = {"flow": "-->", "loop": "-.->", "escalate": "==>"}[e.kind.value]
        lines.append(f"  {a} {arrow}{lab} {b}")
    lines += ["  classDef tool fill:#EEF1F4,stroke:#5A6572", "  classDef review fill:#FFF6E0,stroke:#B7791F",
              "  class " + ",".join(n.id for n in wf.nodes if n.kind.value == "tool") + " tool",
              "  class " + ",".join(n.id for n in wf.nodes if n.kind.value == "review") + " review"]
    return "\n".join(lines) + "\n"


def svg(wf: Workflow) -> str:
    """A layered left-to-right layout (longest path over flow edges), with no external dependencies."""
    idx = GraphIndex(wf)
    layer: dict[str, int] = {}
    for nid in idx.topo:
        preds = [e.source for e in idx.incoming(nid, EdgeKind.FLOW) if e.source in layer]
        layer[nid] = max((layer[p] + 1 for p in preds), default=1)
    cols: dict[int, list[str]] = {}
    for nid in sorted(layer, key=lambda n: wf.node(n).num):
        cols.setdefault(layer[nid], []).append(nid)
    W, H, GX, GY, PAD = 200, 58, 60, 26, 40
    pos = {}
    maxrows = max(len(v) for v in cols.values())
    for c, ids in cols.items():
        top = PAD + 70 + (maxrows - len(ids)) * (H + GY) / 2
        for r, nid in enumerate(ids):
            pos[nid] = (PAD + 90 + (c - 1) * (W + GX), top + r * (H + GY))
    width = PAD * 2 + 90 + len(cols) * (W + GX) + 60
    height = PAD * 2 + 70 + maxrows * (H + GY) + 90
    pos["START"] = (PAD, pos[wf.edges[0].target][1])
    pos["END"] = (width - PAD - 60, pos[next(e.source for e in wf.edges if e.target == "END")][1])
    pos["@escalate"] = (width / 2 - 70, height - PAD - 50)
    fill = {"agent": "#FFFFFF", "tool": "#EEF1F4", "review": "#FFF6E0"}
    parts = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{int(width)}" height="{int(height)}" viewBox="0 0 {int(width)} {int(height)}" '
             'font-family="Helvetica, Arial, sans-serif">',
             '<defs><marker id="a" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" orient="auto-start-reverse">'
             '<path d="M0,0 L10,5 L0,10 z" fill="#1A1F26"/></marker>'
             '<marker id="l" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" orient="auto-start-reverse">'
             '<path d="M0,0 L10,5 L0,10 z" fill="#C4151C"/></marker></defs>',
             f'<rect width="100%" height="100%" fill="#FAFBFC"/>',
             f'<text x="{PAD}" y="{PAD + 10}" font-size="22" font-weight="700" fill="#1A1F26">{html.escape(wf.name)} v{wf.version}</text>',
             f'<text x="{PAD}" y="{PAD + 36}" font-size="13" fill="#5A6572">solid = flow (join = all) · dashed red = bounded loop · dotted = escalate · '
             'white = agent · grey = tool · amber = review · thick red border = human gate</text>']

    def box_edge(nid, side):
        x, y = pos[nid]
        w = W if nid not in ("START", "END", "@escalate") else (60 if nid != "@escalate" else 140)
        return (x + (w if side == "r" else 0), y + H / 2)

    for e in wf.edges:
        (x1, y1), (x2, y2) = box_edge(e.source, "r"), box_edge(e.target, "l")
        if e.kind == EdgeKind.FLOW:
            mx = (x1 + x2) / 2
            parts.append(f'<path d="M{x1:.0f},{y1:.0f} C{mx:.0f},{y1:.0f} {mx:.0f},{y2:.0f} {x2:.0f},{y2:.0f}" fill="none" stroke="#1A1F26" '
                         f'stroke-width="1.4" marker-end="url(#a)"/>')
        elif e.kind == EdgeKind.LOOP:
            sx, sy = pos[e.source][0] + W / 2, pos[e.source][1]
            tx, ty = pos[e.target][0] + W / 2, pos[e.target][1]
            lift = 40 + abs(sx - tx) * 0.06
            parts.append(f'<path d="M{sx:.0f},{sy:.0f} C{sx:.0f},{sy - lift:.0f} {tx:.0f},{ty - lift:.0f} {tx:.0f},{ty:.0f}" fill="none" stroke="#C4151C" '
                         f'stroke-width="1.2" stroke-dasharray="6 4" marker-end="url(#l)" opacity="0.8"><title>{e.id} {html.escape(e.when)}</title></path>')
        else:
            parts.append(f'<path d="M{pos[e.source][0] + W / 2:.0f},{pos[e.source][1] + H:.0f} L{pos["@escalate"][0] + 70:.0f},{pos["@escalate"][1]:.0f}" '
                         f'fill="none" stroke="#5A6572" stroke-width="1.2" stroke-dasharray="2 4" marker-end="url(#a)"/>')
    for nid in ("START", "END"):
        x, y = pos[nid]
        parts.append(f'<rect x="{x}" y="{y}" width="60" height="{H}" rx="29" fill="#1A1F26"/>'
                     f'<text x="{x + 30}" y="{y + H / 2 + 5}" font-size="13" fill="#FFF" text-anchor="middle" font-weight="700">{nid}</text>')
    x, y = pos["@escalate"]
    parts.append(f'<rect x="{x}" y="{y}" width="140" height="{H}" rx="8" fill="#FFF" stroke="#5A6572" stroke-dasharray="2 3"/>'
                 f'<text x="{x + 70}" y="{y + H / 2 + 5}" font-size="13" text-anchor="middle" fill="#1A1F26">@escalate → Wei</text>')
    for n in wf.nodes:
        x, y = pos[n.id]
        stroke, sw = ("#C4151C", 3) if n.human_review.required else ("#5A6572", 1.2)
        parts.append(f'<rect x="{x}" y="{y}" width="{W}" height="{H}" rx="8" fill="{fill[n.kind.value]}" stroke="{stroke}" stroke-width="{sw}">'
                     f'<title>{html.escape(n.purpose)}</title></rect>')
        name = n.name if len(n.name) <= 30 else n.name[:29] + "…"
        parts.append(f'<text x="{x + 10}" y="{y + 22}" font-size="12" font-weight="700" fill="#1A1F26">N{n.num:02d}</text>'
                     f'<text x="{x + 44}" y="{y + 22}" font-size="12" fill="#1A1F26">{html.escape(name)}</text>'
                     f'<text x="{x + 10}" y="{y + 42}" font-size="11" fill="#5A6572">{n.kind.value} · {html.escape(n.agent)}</text>')
    parts.append("</svg>")
    return "\n".join(parts) + "\n"


